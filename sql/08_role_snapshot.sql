USE ROLE ACCOUNTADMIN; USE SECONDARY ROLES ALL;
SELECT role_name, metric_name, ROUND(metric_value, 2) AS val, is_masked
FROM SC_ONTOLOGY.GOVERNANCE.ROLE_VISIBILITY_SNAPSHOT ORDER BY metric_name, role_name;
